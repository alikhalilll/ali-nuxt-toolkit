import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'src/core/inline.generated.ts');

/**
 * `boot.ts` bundled into one minified script, as a string the Vue adapter
 * renders after a server-rendered skeleton. It measures in the first
 * ResizeObserver callback — after layout, before paint — so the first paint
 * already shows the skeleton.
 */
export async function inlineScript() {
  const { outputFiles } = await build({
    entryPoints: [resolve(root, 'src/core/boot.ts')],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2020',
    write: false,
  });
  // `</script` inside would end the element early
  return outputFiles[0].text.trim().replaceAll('</', '<\\/');
}

// Calls the boot a full script earlier in the page left on window, or queues for one still to come.
const STUB = `(s=>{let k=Symbol.for("a-ghost-skeleton.boot"),b=self[k];typeof b=="function"?b(s):(self[k]=b||[]).push(s)})(document.currentScript)`;

const raw = (script) =>
  `// Generated by scripts/build-inline.mjs from boot.ts — don't edit\n` +
  `export const INLINE_SCRIPT = ${JSON.stringify(script)};\n\n` +
  `/** For every skeleton after a page's first: calls the boot INLINE_SCRIPT left on window. */\n` +
  `export const INLINE_STUB = ${JSON.stringify(STUB)};\n\n` +
  `/** Either, as a whole element — for templates where a literal script tag would be read as the component's own. */\n` +
  `export const inlineScriptTag = (nonce?: string, stub = false) =>\n` +
  `  \`<script\${nonce ? \` nonce="\${nonce.replace(/"/g, "&quot;")}"\` : ""}>\${stub ? INLINE_STUB : INLINE_SCRIPT}</script>\`;\n`;

/**
 * Formats the generated file through Prettier so the committed output stays in
 * the repo's canonical style. Without this, `JSON.stringify` emits a
 * double-quoted `INLINE_SCRIPT` with `\"` escapes that re-parses incorrectly
 * in Nitro's Rollup bundler during consumer validation (the escaped inner
 * `"u"` from `typeof window<"u"` breaks the outer string). Prettier
 * rewrites it as a single-quoted literal where no escapes are needed.
 */
export async function source(script) {
  const options = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(raw(script), { ...options, filepath: target });
}

/** What's committed, for a test that it's current. */
export function committed() {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return '';
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await source(await inlineScript());
  if (next !== committed()) writeFileSync(target, next);
}
